export type MarkdownMessage = keyof typeof english;
type MessageValues = Record<string, string | number>;
export type MarkdownTranslator = (message: MarkdownMessage, values?: MessageValues) => string;

function format(message: string, values?: MessageValues) {
  return values ? message.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token)) : message;
}

const chinese: MarkdownTranslator = (message, values) => format(message, values);
const translated: MarkdownTranslator = (message, values) => format(english[message], values);

export function markdownTranslator(locale: MarkdownLocale = "zh-CN"): MarkdownTranslator {
  return locale === "en" ? translated : chinese;
}

export class MarkdownMessageError extends Error {
  constructor(readonly key: MarkdownMessage, readonly values?: MessageValues) {
    super(chinese(key, values));
  }
}
