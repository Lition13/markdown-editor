export type WebMessage = keyof typeof english;
export type WebTranslator = (message: WebMessage, values?: Record<string, string | number>) => string;

function format(message: string, values?: Record<string, string | number>) {
  return values ? message.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token)) : message;
}

const chinese: WebTranslator = (message, values) => format(message, values);
const translated: WebTranslator = (message, values) => format(english[message], values);

export const defaultWebLocale: MarkdownLocale = "en";

export function webTranslator(locale: MarkdownLocale = defaultWebLocale): WebTranslator {
  return locale === "en" ? translated : chinese;
}

export const WebLocale = createContext<MarkdownLocale>(defaultWebLocale);
export const useWebLocale = () => useContext(WebLocale);
export const useWebText = () => webTranslator(useWebLocale());

const units = {
  "zh-CN": { words: ["字词", "字词"], lines: ["行", "行"] },
  en: { words: ["word", "words"], lines: ["line", "lines"] },
};

export function formatDocumentCount(count: number, kind: "words" | "lines", locale: MarkdownLocale) {
  return `${count.toLocaleString(locale)} ${units[locale][kind][count === 1 ? 0 : 1]}`;
}
